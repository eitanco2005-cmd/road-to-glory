#!/usr/bin/env python3
"""Apply docs/data/seo.json (R6A): noindex list + 301 merges. Called by build_site.py before the sitemap.

- noindex: ensures <meta name="robots" content="noindex, follow"> right after <meta charset> (idempotent);
  pages that left the list lose a tag carrying the marker comment.
- redirects: writes docs/_redirects (Netlify, forced 301 so a regenerated old file can never shadow it)
  and rewrites internal links that still point at a merged URL.
    python3 tools/site/seo_rules.py
"""
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
DOCS = REPO / "docs"
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from site_config import BASE_URL as BASE  # noqa: E402
TAG = '<meta name="robots" content="noindex, follow"><!-- seo.json -->'
# Site font (Assistant [+ Noto Sans Hebrew]): load the Google Fonts CSS without blocking render and with
# font-display:optional, so text never re-flows when the web font arrives (was the main CLS source, R6A Lighthouse).
# Only the plain site-font links are touched; apps/invite needs its fonts for canvas drawing and keeps its own link.
FONT_RX = re.compile(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com/css2\?family=Assistant:wght@400;600;700;800(?:&(?:amp;)?family=Noto\+Sans\+Hebrew:wght@400;700)?)&(?:amp;)?display=swap">')


def font_link(m):
    href = m.group(1) + "&display=optional"
    return (f'<link rel="stylesheet" href="{href}" media="print" onload="this.media=\'all\'">'
            f'<noscript><link rel="stylesheet" href="{href}"></noscript>')


def page_file(url):
    return DOCS / url / "index.html" if url.endswith("/") or url == "" else DOCS / url


def main():
    from audit_content import norm_link
    cfg = json.loads((DOCS / "data" / "seo.json").read_text(encoding="utf-8"))
    redirects = cfg.get("redirects", {})
    # a merged page regenerated by an old generator is shadowed by the forced 301; keep it out of the sitemap too
    noindex = set(cfg.get("noindex", [])) | {u for u in redirects if page_file(u).exists()}
    n = 0
    for f in DOCS.rglob("*.html"):
        rel = f.relative_to(DOCS).as_posix()
        if rel.startswith("dl/"):
            continue
        pu = rel[: -len("index.html")] if rel.endswith("index.html") else rel
        s = orig = f.read_text(encoding="utf-8")
        if pu in noindex:
            if not re.search(r'<meta name="robots"[^>]+noindex', s):
                s = re.sub(r"(<meta charset=[^>]*>)", r"\1\n" + TAG, s, count=1)
        elif TAG in s:
            s = s.replace(TAG + "\n", "").replace(TAG, "")
        # hreflang must not point at a page we noindexed (Google ignores / flags such pairs)
        s = re.sub(r'<link rel="alternate" hreflang="[a-zA-Z-]+" href="([^"]+)">\n?',
                   lambda m: "" if m.group(1).replace(BASE, "", 1) in noindex else m.group(0), s)
        if not rel.startswith("apps/invite/"):
            s = FONT_RX.sub(font_link, s)

        def fix(m):
            href = m.group(2)
            t = norm_link(pu, href)
            if t is not None and t in redirects:
                new = redirects[t]
                depth = pu.count("/") if pu.endswith("/") else pu.count("/")
                return m.group(1) + "../" * depth + new + m.group(3)
            return m.group(0)
        if redirects:
            s = re.sub(r'(<a\b[^>]*href=")([^"#?]+)(")', fix, s)
        if s != orig:
            f.write_text(s, encoding="utf-8")
            n += 1
    lines = ["# Generated by tools/site/seo_rules.py from docs/data/seo.json (R6A merges). Do not edit by hand."]
    for src, dst in redirects.items():
        lines.append(f"/{src} /{dst} 301!")
        lines.append(f"/{src}index.html /{dst} 301!")
    (DOCS / "_redirects").write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [u for u in noindex if not page_file(u).exists()]
    for u in missing:
        print("seo_rules: noindex entry has no page:", u)
    print(f"seo_rules: {len(noindex)} noindex, {len(redirects)} redirects, {n} page(s) updated")


if __name__ == "__main__":
    main()
