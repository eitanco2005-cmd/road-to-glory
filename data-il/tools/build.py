#!/usr/bin/env python3
"""Build the Israeli open dataset (data-il/) and its page on the site (docs/data-il/). Zero dependencies.

    python3 data-il/tools/build.py        (also run by tools/site/build_site.py)

Inputs : data-il/tools/hebrew_calendar.py   (holidays, computed)
         data-il/tools/rates_sources.py     (VAT, osek patur, minimum wage, Bituach Leumi — hand-curated, each with a source)
Outputs: data-il/data/*.json + *.csv        (the dataset, CC0)
         data-il/js/israel-data.js          (data block refreshed)
         data-il/python/israel_data/_data.py
         docs/data-il/  (index.html, copies of every data file + israel-data.js, so the site serves downloads)
"""
import csv
import html
import io
import json
import pathlib
import re
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
REPO = ROOT.parent
sys.path.insert(0, str(HERE))
import hebrew_calendar as hc  # noqa: E402
import rates_sources as rs  # noqa: E402

VERSION = rs.CHECKED
SITE = "https://tichnun.netlify.app/"
GH = "https://github.com/eitanco2005-cmd/road-to-glory/tree/main/data-il"
RAW = "https://raw.githubusercontent.com/eitanco2005-cmd/road-to-glory/main/data-il"
YEARS = (2025, 2030)


def write_dataset(name, meta, rows, fields):
    data_dir = ROOT / "data"
    data_dir.mkdir(exist_ok=True)
    doc = dict(meta, license="CC0-1.0", publisher="תכנון פלוס (Tichnun Plus)", homepage=SITE + "data-il/",
               source_repo=GH, generated=VERSION, rows=rows)
    (data_dir / f"{name}.json").write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore", lineterminator="\n")
    w.writeheader()
    for r in rows:
        w.writerow({k: ("" if r.get(k) is None else str(r[k]).lower() if isinstance(r.get(k), bool) else r.get(k)) for k in fields})
    # UTF-8 with BOM so Excel opens the Hebrew correctly
    (data_dir / f"{name}.csv").write_text("﻿" + buf.getvalue(), encoding="utf-8")
    return doc


def main():
    datasets = []
    hol = hc.israeli_holidays(*YEARS)
    datasets.append(("israel-holidays-2025-2030", write_dataset(
        "israel-holidays-2025-2030",
        dict(title="Israeli holidays 2025–2030 (Hebrew + English)", title_he="חגים ומועדים בישראל 2025–2030",
             description="Jewish and Israeli national holidays, fasts and memorial days as observed in Israel (one-day Yom Tov, "
                         "7-day Pesach, Israeli postponement rules), computed with the arithmetic Hebrew calendar and "
                         "cross-checked against two independent libraries (hdate, pyluach). start = first daytime date; holidays "
                         "with begins=sunset_previous_day start the evening before (eve). rest_day = statutory day of rest in Israel.",
             method="data-il/tools/hebrew_calendar.py (Dershowitz & Reingold arithmetic calendar); verified by data-il/tools/verify_holidays.py",
             sources=rs.HOLIDAY_SOURCES),
        hol, ["id", "name_he", "name_en", "type", "start", "end", "days", "begins", "eve", "weekday_en",
              "hebrew_date_he", "hebrew_date_en", "hebrew_year", "rest_day", "note"])))
    for key, ds in rs.DATASETS.items():
        datasets.append((key, write_dataset(key, ds["meta"], ds["rows"], ds["fields"])))

    # ---- helpers: embed the data ----
    embed = dict(
        version=VERSION,
        holidays=[{k: h[k] for k in ("id", "name_he", "name_en", "type", "start", "end", "eve", "rest_day")} for h in hol],
        vat=[{"from": r["from"], "rate": r["rate_percent"]} for r in rs.DATASETS["israel-vat-history"]["rows"]],
        osek_patur=[{"year": r["year"], "ceiling_ils": r["ceiling_ils"]} for r in rs.DATASETS["israel-osek-patur-ceiling"]["rows"]],
        minimum_wage=[{"from": r["from"], "monthly_ils": r["monthly_ils"], "hourly_ils": r["hourly_ils"], "source_url": r["source_url"]}
                      for r in rs.DATASETS["israel-minimum-wage"]["rows"]],
    )
    js_path = ROOT / "js" / "israel-data.js"
    js = js_path.read_text(encoding="utf-8")
    js = re.sub(r"/\*DATA\*/.*?/\*END\*/", lambda m: "/*DATA*/" + json.dumps(embed, ensure_ascii=False, separators=(",", ":")) + "/*END*/", js, flags=re.S)
    js_path.write_text(js, encoding="utf-8")
    (ROOT / "python" / "israel_data" / "_data.py").write_text(
        "# Generated by data-il/tools/build.py from data-il/data/*.json — do not edit. Data: CC0-1.0.\n"
        "import json as _json\n\nDATA = _json.loads(r'''" + json.dumps(embed, ensure_ascii=False) + "''')\n", encoding="utf-8")

    # ---- site copy + page ----
    site = REPO / "docs" / "data-il"
    site.mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "data").iterdir():
        shutil.copy2(f, site / f.name)
    shutil.copy2(js_path, site / "israel-data.js")
    import page  # noqa: E402  (data-il/tools/page.py)
    (site / "index.html").write_text(page.render(datasets, hol, VERSION, SITE, GH, RAW), encoding="utf-8")
    print(f"data-il: {len(hol)} holidays, {len(datasets)} datasets → data-il/data/, docs/data-il/")


if __name__ == "__main__":
    main()
