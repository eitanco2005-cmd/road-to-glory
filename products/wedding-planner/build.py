def demo_guests():
    rnd = random.Random(7)
    rows = []
    for i in range(112):
        fam = FIRST[i % len(FIRST)]
        side = SIDES[i % 3] if i % 7 else "משותף"
        group = GROUPS[(i * 3) % len(GROUPS)]
        couple = rnd.random() < 0.7
        name = f"משפחת {fam}" if couple else f"{PRIV[i % len(PRIV)]} {fam}"
        inv = rnd.choice([2, 2, 2, 3, 4]) if couple else 1
        st = rnd.choices(["מגיעים", "לא מגיעים", "אולי", "טרם ענו", None], [66, 10, 6, 14, 4])[0]
        conf = inv - 1 if (st == "מגיעים" and inv > 2 and rnd.random() < 0.3) else None
        table = (i % 24) + 1 if st == "מגיעים" else None
        gift = None
        gtype = None
        thx = None
        if st == "מגיעים" and rnd.random() < 0.6:
            per = {"משפחה קרובה": 900, "משפחה מורחבת": 500, "חברים": 450}.get(group, 350)
            gift = round(per * (conf or inv) / 50) * 50
            gtype = rnd.choice(["צ'ק", "ביט / פייבוקס", "העברה בנקאית", "צ'ק", "מזומן"])
            thx = "כן" if rnd.random() < 0.4 else None
        rows.append((name, side, group, inv, st, conf, table, gift, gtype, thx))
    return rows


