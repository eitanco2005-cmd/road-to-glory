    title(wM, "תפריט", "מה מגישים ומי מכין. עמודת אלרגנים עוזרת לא לפספס.")
    widths(wM, {"A": 16, "B": 34, "C": 18, "D": 22, "E": 30})
    head(wM, 4, ["מנה", "מה", "מי מכין / מביא", "אלרגנים", "הערות"])
    for i in range(N_MENU):
        r = 5 + i
        v = MENU[i] if i < len(MENU) else (None,) * 4
        who = EX_MENU_WHO.get(i) if example else None
        for col, val in zip("ABCDE", (v[0], v[1], who, v[3] or None, None)):
            cell(wM, f"{col}{r}", val, "in")
    dv_list(wM, ["קערת הסדר", "מנה ראשונה", "מרק", "עיקרית", "תוספת", "קינוח", "שתייה", "אחר"], f"A5:A{4 + N_MENU}")

    # ------------------------------------------------------------ quantities & shopping
    n_rows = len(SHOP) + N_SHOP_X
    Q0, Q1 = 7, 7 + n_rows - 1
    title(wQ, "כמויות וקניות", "כמות = (מבוגרים × למבוגר + ילדים × לילד + לשולחן) × מספר הסדרים × (1 + מרווח ביטחון). המחירים לדוגמה.")
    widths(wQ, {"A": 34, "B": 13, "C": 10, "D": 10, "E": 10, "F": 10, "G": 11, "H": 9, "I": 26, "J": 12, "K": 11, "L": 12, "M": 9})
    cell(wQ, "A3", "עלות קניות משוערת", "sub")
    cell(wQ, "B3", f"=SUM(L{Q0}:L{Q1})", "calc", CUR, bold=True, align="center")
    cell(wQ, "C3", "נקנה", "sub", align="center")
    cell(wQ, "D3", f'=COUNTIF(M{Q0}:M{Q1},"✓")&" / "&COUNTIF(A{Q0}:A{Q1},"?*")', "calc", align="center")
    cell(wQ, "A4", "ספירה לחישוב", "sub")
    cell(wQ, "B4", f'="מבוגרים "&{A_}&" · ילדים "&{K_}&" · סדרים "&{SEDERS}', "calc")
    wQ.merge_cells("B4:F4")
    head(wQ, Q0 - 1, ["פריט", "קטגוריה", "למבוגר", "לילד", "לשולחן", "כמות", "יחידה", "באריזה", "אריזה", "מחיר לאריזה", "אריזות לקנות", "עלות", "נקנה?"])
    for i in range(n_rows):
        r = Q0 + i
        it = SHOP[i] if i < len(SHOP) else (None,) * 9
        name, cat, pa, pc, pt, unit, pack, plabel, price = it
        formulas = {"W": f"=ROUND(4*{ML}/750*{WSHARE},3)", "J": f"=ROUND(4*{ML}/1000*(1-{WSHARE}),3)", "JK": f"=ROUND(4*{ML}/1000,3)",
                    "M": f"=ROUND({KZ}/{KZM},3)", "MK": f"=ROUND({KZ}/{KZM}/2,3)"}
        cell(wQ, f"A{r}", name, "in")
        cell(wQ, f"B{r}", cat, "in", align="center")
        for col, v in zip("CDE", (pa, pc, pt)):
            if isinstance(v, str):
                cell(wQ, f"{col}{r}", formulas[v], "calc", "0.###", align="center")
            else:
                cell(wQ, f"{col}{r}", v, "in", "0.###", align="center")
        cell(wQ, f"F{r}", f'=IF(A{r}="","",ROUND((N(C{r})*{A_}+N(D{r})*{K_}+N(E{r}))*{SEDERS}*(1+{MARGIN}),2))', "calc", "0.##", align="center")
        cell(wQ, f"G{r}", unit, "in", align="center")
        cell(wQ, f"H{r}", pack, "in", "0.##", align="center")
        cell(wQ, f"I{r}", plabel, "in")
        cell(wQ, f"J{r}", price, "in", CUR2, align="center")
        cell(wQ, f"K{r}", f'=IF(OR(A{r}="",N(H{r})=0),"",ROUNDUP(F{r}/H{r},0))', "calc", "0", bold=True, align="center")
        cell(wQ, f"L{r}", f'=IF(K{r}="",0,K{r}*N(J{r}))', "calc", CUR, align="center")
        cell(wQ, f"M{r}", "✓" if example and i in (1, 2, 3, 4, 13, 24) else None, "in", align="center")
    dv_list(wQ, CATS, f"B{Q0}:B{Q1}")
    dv_list(wQ, ["✓"], f"M{Q0}:M{Q1}")
    dv_num(wQ, f"C{Q0}:E{Q1}", 0, 1000)
    cf_fill(wQ, f"A{Q0}:L{Q1}", f'$M{Q0}="✓"', OKF)
    wQ.freeze_panes = f"B{Q0}"
    wQ.auto_filter.ref = f"A{Q0 - 1}:M{Q1}"

    # ------------------------------------------------------------ haggadah roles
    title(wH, "תפקידים בהגדה", "בוחרים מהרשימה מי קורא או מוביל כל קטע (הרשימה נלקחת מגיליון האורחים), או מקלידים שם.")
    widths(wH, {"A": 30, "B": 40, "C": 24, "D": 30})
    head(wH, 4, ["קטע", "מה עושים", "מי מוביל", "הערות / אביזרים"])
    for i in range(len(HAG) + 8):
        r = 5 + i
        v = HAG[i] if i < len(HAG) else (None, None)
        cell(wH, f"A{r}", v[0], "in", bold=True)
        cell(wH, f"B{r}", v[1] or None, "in")
        cell(wH, f"C{r}", EX_HAG.get(i) if example else None, "in", align="center")
        cell(wH, f"D{r}", None, "in")
    # free typing is allowed (names of individual kids are not on the guests sheet), so the list is a suggestion only
    dvh = DataValidation(type="list", formula1=f"={S_GST}!$B${G0}:$B${G1}", allow_blank=True, showErrorMessage=False)
    dvh.add(f"C5:C{4 + len(HAG) + 8}")
    wH.add_data_validation(dvh)

    # ------------------------------------------------------------ timeline
    title(wT, "לוח הכנות", "התאריכים מחושבים מתאריך הסדר שבהגדרות. מסמנים ✓ כשמסיימים.")
    widths(wT, {"A": 12, "B": 13, "C": 62, "D": 16, "E": 9})
    head(wT, 4, ["ימים לפני", "תאריך יעד", "משימה", "אחראי", "בוצע"])
    for i in range(N_TIME):
        r = 5 + i
        d, task = TIMELINE[i] if i < len(TIMELINE) else (None, None)
        cell(wT, f"A{r}", d, "in", "0", align="center")
        cell(wT, f"B{r}", f'=IF(A{r}="","",{S_SET}!$B$4-A{r})', "calc", DATE, align="center")
        cell(wT, f"C{r}", task, "in")
        cell(wT, f"D{r}", None, "in")
        cell(wT, f"E{r}", "✓" if example and i < 4 else None, "in", align="center")
    dv_list(wT, ["✓"], f"E5:E{4 + N_TIME}")
    cf_fill(wT, f"A5:D{4 + N_TIME}", "$E5=\"✓\"", OKF)
    cf_fill(wT, f"B5:B{4 + N_TIME}", 'AND($E5<>"✓",$B5<>"",$B5<TODAY())', WARN)

    # ------------------------------------------------------------ dashboard
    title(wD, "דשבורד ליל הסדר 2027", "מתעדכן לבד מכל הגיליונות.")
    widths(wD, {"A": 32, "B": 16, "C": 30, "E": 18, "F": 14})
    shop_rng = lambda c: f"{S_SHOP}!${c}${Q0}:${c}${Q1}"  # noqa: E731
    kpi(wD, 4, "ימים עד ליל הסדר", f"=MAX(0,{S_SET}!B4-TODAY())", "0")
    kpi(wD, 5, "מבוגרים", f"={A_}", "0")
    kpi(wD, 6, "ילדים", f"={K_}", "0")
    kpi(wD, 7, "מצות יד שמורות", f'=SUMIF({shop_rng("A")},"מצה שמורה*",{shop_rng("F")})', "0.#", "כולל מרווח ביטחון")
    kpi(wD, 8, "בקבוקי יין (ארבע כוסות)", f'=SUMIF({shop_rng("A")},"יין לארבע*",{shop_rng("K")})', "0")
    kpi(wD, 9, "ליטרים מיץ ענבים", f'=SUMIF({shop_rng("A")},"מיץ ענבים*",{shop_rng("K")})', "0")
    kpi(wD, 10, "עלות קניות משוערת", f"={S_SHOP}!B3", CUR)
    kpi(wD, 11, "תקציב", f"={S_SET}!B15", CUR)
    kpi(wD, 12, "נותר בתקציב", '=IF(B11="","",B11-B10)', CUR, "מספר שלילי = חריגה")
    kpi(wD, 13, "עלות לסועד", '=IF(B5+B6=0,0,B10/(B5+B6))', CUR)
    kpi(wD, 14, "משימות שבוצעו", f'=COUNTIF({S_TIME}!E5:E{4 + N_TIME},"✓")&" / "&COUNTIF({S_TIME}!C5:C{4 + N_TIME},"?*")')
    cf_fill(wD, "B12", 'AND(B12<>"",B12<0)', WARN)
    head(wD, 3, ["קטגוריה", "עלות"], col0=5)
    for i, c in enumerate(CATS):
        r = 4 + i
        cell(wD, f"E{r}", c, "calc")
        cell(wD, f"F{r}", f'=SUMIF({shop_rng("B")},E{r},{shop_rng("L")})', "calc", CUR, align="center")
    bar(wD, "A17", "עלות לפי קטגוריה (₪)", wD, Reference(wD, min_col=5, min_row=4, max_row=3 + len(CATS)),
        Reference(wD, min_col=6, min_row=3, max_row=3 + len(CATS)), number_format="#,##0")
    pie(wD, "H3", "חלוקת העלות", Reference(wD, min_col=5, min_row=4, max_row=3 + len(CATS)),
        Reference(wD, min_col=6, min_row=3, max_row=3 + len(CATS)))
    wb.active = 7 if example else 0
    return wb


