def demo_guests():
    rnd = random.Random(11)
    rows = []
    for i in range(60):
        side = SIDES[i % 4]
        if side == SIDES[2]:
            name, inv, group = f"{KIDS[i % len(KIDS)]} {NAMES[(i * 7) % 20]}", 1, rnd.choice(GROUPS[2:4])
        else:
            name, inv, group = f"משפחת {NAMES[i % 20]}", rnd.choice([2, 2, 3, 4]), rnd.choice(
                GROUPS[:2] if side in SIDES[:2] else GROUPS[4:])
        st = rnd.choices(["מגיעים", "לא מגיעים", "אולי", "טרם ענו"], [65, 10, 8, 17])[0]
        table = (i % 14) + 1 if st == "מגיעים" else None
        gift = gtype = thx = None
        if st == "מגיעים" and rnd.random() < 0.55:
            per = 180 if inv == 1 else {"משפחה קרובה": 500, "משפחה מורחבת": 300}.get(group, 250)
            gift = per if inv == 1 else per + 100 * (inv - 2)
            gift = int(round(gift / 18.0) * 18) if gift else None  # multiples of 18 (חי)
            gtype = rnd.choice(["צ'ק", "ביט / פייבוקס", "מזומן", "מתנה" if inv == 1 else "צ'ק"])
            if gtype == "מתנה":
                gift = None
            thx = "כן" if rnd.random() < 0.3 else None
        rows.append((name, side, group, inv, st, None, table, gift, gtype, thx))
    return rows


